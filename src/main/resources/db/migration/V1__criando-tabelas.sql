CREATE TABLE solicitacao
(
    id NUMBER (38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo VARCHAR2 (255) NOT NULL,
    descricao VARCHAR2 (255) NOT NULL,
    prioridade VARCHAR2 (255),
    status VARCHAR2 (255),
    usuario_id NUMBER (38, 0) NOT NULL,
    tipo_id NUMBER (38, 0) NOT NULL,
    CONSTRAINT pk_solicitacao PRIMARY KEY (id)
);

CREATE TABLE tipo_solicitacao
(
    id NUMBER (38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome VARCHAR2 (255) NOT NULL,
    CONSTRAINT pk_tiposolicitacao PRIMARY KEY (id)
);

CREATE TABLE usuario
(
    id NUMBER (38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome VARCHAR2 (255) NOT NULL,
    email VARCHAR2 (255) NOT NULL,
    setor VARCHAR2 (255) NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id)
);

