UPDATE usuario
SET setor = CASE UPPER(setor)
    WHEN 'ATENDIMENTO' THEN 'ATENDIMENTO'
    WHEN 'COMERCIAL' THEN 'COMERCIAL'
    WHEN 'COMPRAS' THEN 'COMPRAS'
    WHEN 'FINANCEIRO' THEN 'FINANCEIRO'
    WHEN 'JURIDICO' THEN 'JURIDICO'
    WHEN 'MARKETING' THEN 'MARKETING'
    WHEN 'OPERACOES' THEN 'OPERACOES'
    WHEN 'RH' THEN 'RH'
    WHEN 'TI' THEN 'TI'
    ELSE setor
END;

ALTER TABLE usuario ADD CONSTRAINT usuario_setor_ck
    CHECK (setor IN (
        'ATENDIMENTO', 'COMERCIAL', 'COMPRAS', 'FINANCEIRO', 'JURIDICO',
        'MARKETING', 'OPERACOES', 'RH', 'TI'
    ));
